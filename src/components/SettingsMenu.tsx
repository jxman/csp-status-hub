const MODE_OPTIONS: { id: ThemeMode; label: string; icon: JSX.Element }[] = [
  { id: 'light', label: 'Light', icon: <SunIcon /> },
  { id: 'dark', label: 'Dark', icon: <MoonIcon /> },
  { id: 'system', label: 'System', icon: <MonitorIcon /> },
];

export function SettingsMenu({ mode, onModeChange, onShowAbout }: Props) {
  const [open, setOpen] = useState(false);
  const rootRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!open) return;

    function handleClickOutside(e: MouseEvent) {
      if (rootRef.current && !rootRef.current.contains(e.target as Node)) {
        setOpen(false);
      }
    }
    function handleEscape(e: KeyboardEvent) {
      if (e.key === 'Escape') setOpen(false);
    }

    document.addEventListener('mousedown', handleClickOutside);
    document.addEventListener('keydown', handleEscape);
    return () => {
      document.removeEventListener('mousedown', handleClickOutside);
      document.removeEventListener('keydown', handleEscape);
    };
  }, [open]);

  return (
    <div className="settings-root" ref={rootRef}>
      <button
        className="icon-btn"
        onClick={() => setOpen((o) => !o)}
        aria-label="Settings"
        aria-expanded={open}
        title="Settings"
      >
        <GearIcon />
      </button>

      {open && (
        <div className="settings-panel" role="menu">
          <div className="settings-section-label">Appearance</div>
          <div className="settings-theme-switch">
            {MODE_OPTIONS.map((opt) => (
              <button
                key={opt.id}
                className={`settings-theme-opt${mode === opt.id ? ' active' : ''}`}
                onClick={() => onModeChange(opt.id)}
                role="menuitemradio"
                aria-checked={mode === opt.id}
              >
                {opt.icon}
                {opt.label}
              </button>
            ))}
          </div>

          <div className="settings-divider" />

          <button
            className="settings-menu-item"
            onClick={() => { setOpen(false); onShowAbout(); }}
            role="menuitem"
          >
            <InfoIcon /> About
          </button>

          <a
            className="settings-menu-item settings-menu-item--coffee"
            href="https://buymeacoffee.com/synepho"
            target="_blank"
            rel="noopener noreferrer"
            onClick={() => setOpen(false)}
            role="menuitem"
          >
            <CoffeeIcon /> Buy me a coffee
          </a>
        </div>
      )}
    </div>
  );
}
